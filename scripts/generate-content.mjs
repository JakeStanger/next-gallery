// Inlines the files in content/ (markdown, svg) into a generated module.
//
// Cloudflare Workers have no access to the project filesystem at runtime, so
// pages that read content during ISR revalidation can't use fs.readFileSync.
// Run automatically on install, dev and build; output is gitignored.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const contentDir = path.join(root, 'content');
const outFile = path.join(root, 'lib', 'gen', 'content.ts');

const extensions = new Set(['.md', '.svg']);

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(fullPath);
    return extensions.has(path.extname(entry.name)) ? [fullPath] : [];
  });
}

const files = Object.fromEntries(
  walk(contentDir)
    .sort()
    .map((file) => [
      path.relative(contentDir, file).split(path.sep).join('/'),
      fs.readFileSync(file, 'utf8'),
    ])
);

const source = `// Generated by scripts/generate-content.mjs - do not edit.
const files: Record<string, string> = ${JSON.stringify(files, null, 2)};

export default files;
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, source);
console.log(`Inlined ${Object.keys(files).length} content files into ${path.relative(root, outFile)}`);
